const LANG_KEY = 'ajwa.lang'

function storedBangla(): boolean {
  try {
    return localStorage.getItem(LANG_KEY) !== 'en'
  } catch {
    return true
  }
}

/** Bangla is the default, as on the phone; the choice is remembered per browser. */
export let bangla = storedBangla()

export function setBangla(value: boolean) {
  bangla = value
  try {
    localStorage.setItem(LANG_KEY, value ? 'bn' : 'en')
  } catch {
    // Private mode: the choice lasts for this visit only.
  }
  document.documentElement.lang = value ? 'bn' : 'en'
}

/** Looks up a string and fills %1$s, %2$s… placeholders. */
export function t(key: StringKey, ...args: (string | number)[]): string {
  let s: string = (bangla ? bn : en)[key]
  args.forEach((a, i) => {
    s = s.replace(`%${i + 1}$s`, String(a))
  })
  return s
}

export function unitLabel(unit: string | null | undefined): string {
  return unit && `unit_${unit}` in bn ? t(`unit_${unit}` as StringKey) : unit ?? ''
}
